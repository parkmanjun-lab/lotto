import {isDeepStrictEqual} from 'node:util';
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {FIRST,WEEK,validateDraws} from '../lib/lotto.mjs';

export const CLIENT_HISTORY_ALPHABET='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrs';
const root=fileURLToPath(new URL('..',import.meta.url));

// Dates and rounds are omitted only after proving that they can be recovered
// exactly. The canonical JSON remains the sole source of history and metadata.
export function encodeClientHistory(snapshot,now=Date.now()){
  validateDraws(snapshot?.draws,now);
  if(typeof snapshot?.metadata?.retrievedAt!=='string'||!Number.isFinite(Date.parse(snapshot.metadata.retrievedAt)))throw Error('Client history requires a valid retrievedAt timestamp.');
  let encoded='';
  for(const [index,draw] of snapshot.draws.entries()){
    const date=new Date(FIRST+index*WEEK).toISOString().slice(0,10);
    if(draw.round!==index+1||draw.date!==date)throw Error('Client history must be ordered, contiguous, weekly draws starting at round 1.');
    encoded+=[...draw.numbers,draw.bonus].map(number=>CLIENT_HISTORY_ALPHABET[number-1]).join('');
  }
  const draws=Array.from({length:encoded.length/7},(_,index)=>{
    const values=Array.from(encoded.slice(index*7,index*7+7),character=>CLIENT_HISTORY_ALPHABET.indexOf(character)+1);
    return{round:index+1,date:new Date(FIRST+index*WEEK).toISOString().slice(0,10),numbers:values.slice(0,6),bonus:values[6]};
  });
  if(!isDeepStrictEqual(draws,snapshot.draws))throw Error('Client history round-trip would change the canonical draws.');
  return{encoded,retrievedAt:snapshot.metadata.retrievedAt};
}

export function renderClientHistory(snapshot,now=Date.now()){
  const {encoded,retrievedAt}=encodeClientHistory(snapshot,now);
  return `// Generated by scripts/build-client-history.mjs from history.json. Do not edit.
// The build verifies every round, date, number and bonus before omitting redundant fields.
import type {Draw} from '../lotto.mjs';
const alphabet=${JSON.stringify(CLIENT_HISTORY_ALPHABET)};
const encoded=${JSON.stringify(encoded)};
const first=Date.UTC(2002,11,7),week=7*86400000;
if(encoded.length%7!==0)throw Error('Invalid bundled history length.');
// This decoder is clock-independent: Workers can import it before a request clock exists.
const draws:Draw[]=Array.from({length:encoded.length/7},(_,index)=>{
  const values=Array.from(encoded.slice(index*7,index*7+7),character=>alphabet.indexOf(character)+1);
  if(values.some(number=>number<1))throw Error('Invalid bundled history character.');
  return{round:index+1,date:new Date(first+index*week).toISOString().slice(0,10),numbers:values.slice(0,6),bonus:values[6]};
});
const snapshot={metadata:{retrievedAt:${JSON.stringify(retrievedAt)}},draws};
export default snapshot;
`;
}

export function buildClientHistory(){
  const input=resolve(root,'lib/data/history.json'),output=resolve(root,'lib/data/history-client.ts');
  const snapshot=JSON.parse(readFileSync(input,'utf8')),source=renderClientHistory(snapshot);
  if(!existsSync(output)||readFileSync(output,'utf8')!==source)writeFileSync(output,source);
  return{output,rounds:snapshot.draws.length,bytes:Buffer.byteLength(source)};
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const result=buildClientHistory();
  console.log(`Client history: ${result.rounds} verified rounds, ${result.bytes} source bytes.`);
}
