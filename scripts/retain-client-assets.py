#!/usr/bin/env python3
"""Keep only hashed public JS/CSS from explicitly supplied prior release archives.
Usage: python3 scripts/retain-client-assets.py archive-vN.tar.gz archive-vM.tar.gz
Run before the new build; pass the last two deployed releases, never previews.
This deliberately does not retain HTML, RSC, source maps, API code, or credentials.
"""
import hashlib,json,pathlib,re,sys,tarfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
PATTERN=re.compile(r'^dist/client/(_next/static/(?:chunks/[A-Za-z0-9_-]+-[A-Za-z0-9_-]+\.js|css/[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.css))$')
if len(sys.argv)!=3: raise SystemExit('Supply exactly the last two deployed archives')
manifest_path=ROOT/'scripts/retained-client-assets.json'
previous=json.loads(manifest_path.read_text()) if manifest_path.exists() else {'files':{}}
for key,sha in previous['files'].items():
 old=ROOT/'compat/client'/key
 if not old.is_file() or hashlib.sha256(old.read_bytes()).hexdigest()!=sha: raise ValueError('Existing retained asset differs from recorded generated bytes')
assets={}; releases=[]
for name in sys.argv[1:]:
 p=pathlib.Path(name); names=[]
 with tarfile.open(p,'r:gz') as archive:
  build_manifest=json.load(archive.extractfile('dist/client/.vite/manifest.json'))
  owned=set()
  for entry in build_manifest.values():
   owned.add(entry.get('file',''));owned.update(entry.get('css',[]))
  rsc_manifest=archive.extractfile('dist/server/__vite_rsc_assets_manifest.js').read().decode()
  # Only public resource paths are read; no server code is copied.
  owned.update(re.findall(r'"/(_next/static/css/[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.css)"',rsc_manifest))
  for member in archive.getmembers():
   match=PATTERN.fullmatch(member.name)
   if not match or match[1] not in owned: continue
   if not member.isfile() or member.size>2_000_000: raise ValueError('Invalid asset type/size')
   data=archive.extractfile(member).read();key=match[1]
   if key in assets and assets[key]!=data: raise ValueError('Same hash filename has different content')
   assets[key]=data;names.append(key)
 if not names: raise ValueError('No client hashed assets found')
 releases.append({'archive':p.name,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'assets':sorted(names)})
if len(assets)>60 or sum(map(len,assets.values()))>4_000_000: raise ValueError('Retention budget exceeded')
for key,data in assets.items():
 p=ROOT/'compat/client'/key
 if p.exists() and p.read_bytes()!=data: raise ValueError('Conflicting retained content')
 p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
# Only obsolete generated files verified against the previous recorded SHA are pruned.
for key in previous['files']:
 if key not in assets: (ROOT/'compat/client'/key).unlink()
# Other files are never removed; the build's exact-set guard rejects any unexpected files.
manifest={'releases':releases,'files':{key:hashlib.sha256(data).hexdigest() for key,data in sorted(assets.items())}}
(ROOT/'scripts/retained-client-assets.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(f'Retained {len(assets)} public assets, {sum(map(len,assets.values()))} bytes; no HTML/server files')
